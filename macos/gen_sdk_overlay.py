# ent::Entity: the fork's view of the components storage (ComponentsStorage at 0x70, its DynArray at +0x30 = 0xA0, the same
# bytes the macOS SDK names componentsStorage[0x30] + components) and the fork's GetComponent helpers.
patch("RED4ext/Scripting/Natives/entEntity.hpp", [
    ("#include <RED4ext/Common.hpp>\n",
     "#include <RED4ext/Common.hpp>\n#include <RED4ext/RTTISystem.hpp>\n"),
    ("    uint8_t componentsStorage[0x30];           // 70 - ComponentsStorage but without Handle?\n"
     "    DynArray<Handle<IComponent>> components;   // A0 - Part of ComponentsStorage\n",
     "    // LTBF R41: the jackhumbert fork's ComponentsStorage view of the same bytes (its DynArray is at +0x30).\n"
     "    struct ComponentsStorageView\n"
     "    {\n"
     "        uint8_t unk00[0x30];                    // 70\n"
     "        DynArray<Handle<IComponent>> components; // A0\n"
     "    } componentsStorage;                        // 70\n"),
    ("    static constexpr const char* ALIAS = \"Entity\";\n",
     "    static constexpr const char* ALIAS = \"Entity\";\n\n"
     "    // LTBF R41: jackhumbert fork helpers (same bodies as the fork's entEntity.hpp)\n"
     "    template<class T>\n"
     "    Handle<T> GetComponent()\n"
     "    {\n"
     "        auto rtti = CRTTISystem::Get();\n"
     "        Handle<T> result;\n"
     "        for (auto const& handle : this->componentsStorage.components)\n"
     "        {\n"
     "            auto component = handle.GetPtr();\n"
     "            if (component->GetNativeType() == rtti->GetClass(T::NAME))\n"
     "            {\n"
     "                result.instance = reinterpret_cast<T*>(component);\n"
     "                result.refCount = handle.refCount;\n"
     "                result.refCount->IncRef();\n"
     "                break;\n"
     "            }\n"
     "        }\n"
     "        return result;\n"
     "    }\n\n"
     "    template<class T>\n"
     "    Handle<T> GetComponent(CName aName)\n"
     "    {\n"
     "        auto rtti = CRTTISystem::Get();\n"
     "        Handle<T> result;\n"
     "        for (auto const& handle : this->componentsStorage.components)\n"
     "        {\n"
     "            auto component = handle.GetPtr();\n"
     "            if (component->GetNativeType() == rtti->GetClass(T::NAME) && component->name == aName)\n"
     "            {\n"
     "                result.instance = reinterpret_cast<T*>(component);\n"
     "                result.refCount = handle.refCount;\n"
     "                result.refCount->IncRef();\n"
     "                break;\n"
     "            }\n"
     "        }\n"
     "        return result;\n"
     "    }\n"),
])

