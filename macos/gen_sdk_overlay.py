#!/usr/bin/env python3
"""LTBF R41 (macOS): generate patched copies of a few macOS RED4ext SDK headers into the build's sdk-overlay directory.

The jackhumbert fork that LTBF is written against adds small helpers to core SDK headers (ISerializable::IsOfClass,
StaticArray::operator[], CRUID::Next, Entity::GetComponent, ...). The macOS SDK does not have them. Instead of copying whole core
headers, each patch below takes the macOS SDK file as it is and inserts the fork's helper at an anchor line. A missing anchor
stops the configure step (the SDK changed; update the patch). Run by macos/CMakeLists.txt at configure time:

    gen_sdk_overlay.py <macOS SDK include dir> <output overlay dir>
"""
import os
import sys

SDK, OUT = sys.argv[1], sys.argv[2]

NOTE = "// LTBF R41 (macOS): generated by let_there_be_flight/macos/gen_sdk_overlay.py from the macOS SDK file; do not edit.\n"


def patch(rel, edits, append=""):
    src = os.path.join(SDK, rel)
    text = open(src).read()
    for anchor, replacement in edits:
        if text.count(anchor) != 1:
            sys.exit(f"gen_sdk_overlay: anchor not found exactly once in {rel}: {anchor!r}")
        text = text.replace(anchor, replacement)
    text = text.replace("#pragma once\n", "#pragma once\n" + NOTE, 1)
    text += append
    dst = os.path.join(OUT, rel)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    old = open(dst).read() if os.path.exists(dst) else None
    if old != text:
        open(dst, "w").write(text)


# ISerializable::IsOfClass (fork API): walks the native type's parent chain.
patch("RED4ext/ISerializable.hpp", [(
    "    WeakHandle<ISerializable> ref;",
    "    bool IsOfClass(const CClass* aClass); // LTBF R41: jackhumbert fork helper\n\n"
    "    WeakHandle<ISerializable> ref;")])
patch("RED4ext/ISerializable-inl.hpp", [], append="""
// LTBF R41: jackhumbert fork helper (same body as the fork's ISerializable-inl.hpp).
RED4EXT_INLINE bool RED4ext::ISerializable::IsOfClass(const RED4ext::CClass* aClass)
{
    auto type = this->GetNativeType();
    bool isOfClass = false;
    do
    {
        isOfClass |= type == aClass;
    } while ((type = type->parent));
    return isOfClass;
}
""")

# StaticArray::operator[] and CRUID::Next (fork API). On macOS CRUID::Next asks the plugin (macos/MacShims.cpp): the game's
# counter once R41b has its RVA, a plugin counter in a separate band until then.
patch("RED4ext/NativeTypes.hpp", [
    ("struct CRUID\n{\n",
     "extern \"C\" int64_t ltbf_mac_cruid_next();\n\n"
     "struct CRUID\n{\n"
     "    // LTBF R41: jackhumbert fork helper. Windows: (InterlockedIncrement64(counter) * 4) | 1 on the game's counter.\n"
     "    static inline CRUID Next()\n"
     "    {\n"
     "        CRUID id;\n"
     "        id.unk00 = ltbf_mac_cruid_next();\n"
     "        return id;\n"
     "    }\n\n"),
    ("struct StaticArray\n{\n",
     "struct StaticArray\n{\n"
     "    // LTBF R41: jackhumbert fork helpers\n"
     "    const T& operator[](uint32_t aIndex) const\n"
     "    {\n"
     "        return entries[aIndex];\n"
     "    }\n\n"
     "    T& operator[](uint32_t aIndex)\n"
     "    {\n"
     "        return entries[aIndex];\n"
     "    }\n\n"),
])

