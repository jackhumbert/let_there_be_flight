r"""Landing pad numbers: each listed pad gets a number for good, painted on its deck and shown in its pin
(docs/design/landing-pads.md, "Pad numbers").

The numbers live in pad_numbers.json (pad id -> number). This tool keeps it: a listed pad without a number gets
the next free one, and a number is never reused, also after its pad leaves the list (the entry stays). Hand edits
there are kept. New pads are numbered in map reading order: bands of BAND metres from north to south, west to east
in each band, so neighbours get nearby numbers.

  python pad_numbers.py number [--tsv ../../src/navigation/helipads.tsv]
      writes the numbers into the TSV's number column (pads.py build does the same when it writes the TSV)
  python pad_numbers.py signs --work <pads.py work dir>
      paints them: finds each numbered pad's vanilla marking in <work>/placements.json (pads.py scan) and writes
        - pad_number_signs.json: one sign per pad at its marking (read by pad_sector.py, which places it);
        - the generated block of src/navigation/hidden_nodes.txt: the vanilla "28" sign under each of ours;
        - the number entity (ltbf_pad_number.ent / .app in the archive source): one appearance per number, the
          ring and the digits (pad_number_assets.py) as mesh components.
      then: python pad_sector.py; python ../packaging/pack_archive.py

A sign goes where the vanilla "28" sign (landing_pad_b_01) is, at its transform; on a pad with the square
border alone (landing_pad_a_01) at the border's centre, turned 90 degrees from it as the vanilla sign always is.
Digits sit along the sign's local X: the texture's left edge is at +X (the vanilla quad's UVs), so the first
digit goes on the +X side, one digit DIGIT_STEP[n] from the next (a multiple of the diode grid's pitch), three digits
smaller (DIGIT_SCALE) so they fit inside the ring.
"""

import argparse
import copy
import json
import math
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))  # tools/, for common
from common import paths  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
NUMBERS = os.path.join(HERE, "pad_numbers.json")
SIGNS = os.path.join(HERE, "pad_number_signs.json")
TSV = os.path.join(REPO, "src", "navigation", "helipads.tsv")
HIDDEN = os.path.join(REPO, "src", "navigation", "hidden_nodes.txt")
SOURCE = os.path.join(REPO, "src", "wolvenkit", "source", "archive")
DEPOT_DIR = r"user\jackhumbert\pads"
ENTITY = DEPOT_DIR + r"\ltbf_pad_number.ent"
SECTOR_DIR = r"base\worlds\03_night_city\_compiled\default"
BAND = 500.0
# the deck paints up to three digits
MAX_NUMBER = 999
# the vanilla sign: 5 m quad, diode grid 60 x 60 (DiodesTilingAndScrollSpeed), so a pitch of 5 / 60 m
PITCH = 5.0 / 60.0
# the glyphs are 22 px of the sign's 128 (0.86 m) with the vanilla pair 37 px (1.45 m) apart: two digits 17 pitches
# apart (1.42 m, a 14 px gap); three at that spacing do not fit inside the ring, so they are drawn at DIGIT_SCALE,
# 14 pitches (1.17 m, an 11 px gap) apart
GLYPH_W = 22 * 5.0 / 128
DIGIT_STEP = {1: 0.0, 2: 17 * PITCH, 3: 14 * PITCH}
DIGIT_SCALE = {1: 1.0, 2: 1.0, 3: 0.85}
LIFT = 0.015  # ring 1.5 cm over the vanilla paint, digits 3 cm: on one deck (pad 99) 2 mm left it under the surface
MATCH_XY, MATCH_Z = 2.0, 4.0  # the nav map floor can sit 3.4 m over the paint (a row of bays at -300, -1495)
# prefab pads with a plain solid deck and no marking: painted in the middle (the v2 and Charter Hill decks are
# grating, the v3 and v4 ones show the 28 in their proxy's texture)
# prefab -> the deck's centre in the prefab's frame (the middle of its proxy mesh's bounds, X -7.29..1.5,
# Y -5.75..5.99): the prefab's origin is at one end of the deck
PAINTED_PREFABS = {"av_landing_pad_a_v3_small": (-2.9, 0.12)}
HIDDEN_BEGIN ="# --- generated by tools/pads/pad_numbers.py signs: the vanilla 28 under each pad number ---"
HIDDEN_END = "# --- end of pad_numbers.py ---"


def reading_order(pos):
    x, y = pos[0], pos[1]
    return (-int(y // BAND), x)


def load(path=NUMBERS):
    if not os.path.exists(path):
        return {}
    return {k: int(v) for k, v in json.load(open(path, encoding="utf-8"))["numbers"].items()}


def save(numbers, path=NUMBERS):
    doc = {
        "comment": "Landing pad numbers, pad id -> number (tools/pads/pad_numbers.py keeps it). A number is never "
                   "reused: an entry stays after its pad leaves the list. Hand edits are kept.",
        "numbers": dict(sorted(numbers.items(), key=lambda kv: kv[1])),
    }
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(doc, f, indent=1)
        f.write("\n")


def assign(pads, numbers):
    """Numbers for `pads` ({id: (x, y)}): the kept ones, new pads after the highest number ever given, in
    reading order. Returns the updated map (all old entries included)."""
    out = dict(numbers)
    values = list(out.values())
    if len(set(values)) != len(values):
        dupes = sorted({n for n in values if values.count(n) > 1})
        raise SystemExit(f"{NUMBERS}: numbers given twice: {dupes}")
    nxt = max(values, default=0) + 1
    for pad_id in sorted((p for p in pads if p not in out), key=lambda p: reading_order(pads[p])):
        out[pad_id] = nxt
        nxt += 1
    if nxt - 1 > MAX_NUMBER:
        raise SystemExit(f"pad numbers past {MAX_NUMBER}: the deck paints three digits at most")
    return out


def read_tsv(path):
    head, rows = [], []
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if not line or line.startswith("#"):
            head.append(line)
            continue
        f = line.split("\t")
        f += [""] * (9 - len(f))
        rows.append(f)
    return head, rows


def number_tsv(path, numbers_path=NUMBERS):
    head, rows = read_tsv(path)
    numbers = assign({r[0]: (float(r[1]), float(r[2])) for r in rows}, load(numbers_path))
    save(numbers, numbers_path)
    for r in rows:
        r[8] = str(numbers[r[0]])
    head = [h + "\tnumber" if h.startswith("# id\t") and not h.endswith("\tnumber") else h for h in head]
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        for h in head:
            f.write(h + "\n")
        for r in rows:
            f.write("\t".join(r[:9]) + "\n")
    print(f"numbered {len(rows)} pads in {path} (highest {max(numbers.values(), default=0)})", file=sys.stderr)


