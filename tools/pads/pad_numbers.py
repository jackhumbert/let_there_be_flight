def digit_offsets(n):
    """Local X of each digit of n, first digit first."""
    digits = str(n)
    step = DIGIT_STEP[len(digits)]
    first = step * (len(digits) - 1) / 2.0
    return [(int(d), first - i * step) for i, d in enumerate(digits)]


def find_signs(rows, placements):
    """One sign per numbered pad: {pad, number, pos, yaw, hide} at its vanilla marking; pads with no marking are
    returned apart."""
    b01 = [p for p in placements if p["mesh"] == "landing_pad_b_01"]
    a01 = [p for p in placements if p["mesh"] == "landing_pad_a_01"]
    by_id = {p["id"]: p for p in placements}

    def near(cands, x, y, z):
        hits = [p for p in cands if math.hypot(p["pos"][0] - x, p["pos"][1] - y) < MATCH_XY
                and abs(p["pos"][2] - z) < MATCH_Z]
        return min(hits, key=lambda p: math.hypot(p["pos"][0] - x, p["pos"][1] - y)) if hits else None

    signs, bare = [], []
    for r in rows:
        x, y, z, number = float(r[1]), float(r[2]), float(r[3]), int(r[8])
        m = near(b01, x, y, z)
        if m:
            sector, index = m["id"].split("/")
            signs.append({"pad": r[0], "number": number, "pos": [round(v, 4) for v in m["pos"]],
                          "yaw": round(m["yaw"] % 360.0, 3), "over": "landing_pad_b_01",
                          "hide": {"sector": sector, "index": int(index), "x": m["pos"][0], "y": m["pos"][1]}})
            continue
        m = near(a01, x, y, z)
        if m:
            signs.append({"pad": r[0], "number": number, "pos": [round(v, 4) for v in m["pos"]],
                          "yaw": round((m["yaw"] + 90.0) % 360.0, 3), "over": "landing_pad_a_01", "hide": None})
            continue
        prefab = by_id.get(r[0])
        if prefab and prefab["mesh"] in PAINTED_PREFABS:
            # a plain deck with no marking of its own: the sign in its middle, on the prefab's heading, at the
            # deck height the pad list has
            ox, oy = PAINTED_PREFABS[prefab["mesh"]]
            yaw = math.radians(prefab["yaw"])
            cx = prefab["pos"][0] + ox * math.cos(yaw) - oy * math.sin(yaw)
            cy = prefab["pos"][1] + ox * math.sin(yaw) + oy * math.cos(yaw)
            signs.append({"pad": r[0], "number": number, "pos": [round(cx, 4), round(cy, 4), z],
                          "yaw": round(prefab["yaw"] % 360.0, 3), "over": prefab["mesh"], "hide": None})
            continue
        bare.append(r[0])
    return signs, bare


def write_hidden(signs, path=HIDDEN):
    """Replace the generated block of hidden_nodes.txt (the hand-written lines stay)."""
    text = open(path, encoding="utf-8").read()
    pattern = re.compile(re.escape(HIDDEN_BEGIN) + r".*?" + re.escape(HIDDEN_END) + r"\n?", re.S)
    text = pattern.sub("", text).rstrip("\n") + "\n"
    by_sector = {}
    for s in signs:
        if s["hide"]:
            by_sector.setdefault(s["hide"]["sector"], []).append(s)
    lines = [HIDDEN_BEGIN]
    for sector in sorted(by_sector):
        lines.append(f"S {SECTOR_DIR}\\{sector}.streamingsector")
        for s in sorted(by_sector[sector], key=lambda s: s["hide"]["index"]):
            h = s["hide"]
            lines.append(f"I {h['index']} {h['x']} {h['y']}")
    lines.append(HIDDEN_END)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text + "\n".join(lines) + "\n")


def cname(s):
    return {"$type": "CName", "$storage": "string", "$value": str(s)}


def renumber(doc):
    """HandleIds and BufferIds 0, 1, 2, ... in document order, as WolvenKit expects."""
    n, b = [0], [0]

    def walk(o):
        if isinstance(o, dict):
            if "HandleId" in o:
                o["HandleId"] = str(n[0])
                n[0] += 1
            if "BufferId" in o:
                o["BufferId"] = str(b[0])
                b[0] += 1
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)

    walk(doc)
    return doc


def mesh_component(tpl, name, mesh, x, z, index, scale=1.0):
    c = copy.deepcopy(tpl)
    c["id"] = str(0x3100000000000000 + index)
    c["name"] = cname(name)
    c["mesh"]["DepotPath"]["$value"] = mesh
    c["castShadows"] = c["castLocalShadows"] = "Never"
    c["castRayTracedGlobalShadows"] = c["castRayTracedLocalShadows"] = "Never"
    pos = c["localTransform"]["Position"]
    pos["x"]["Bits"] = int(round(x * 131072.0))
    pos["z"]["Bits"] = int(round(z * 131072.0))
    c["visualScale"] = {"$type": "Vector3", "X": scale, "Y": scale, "Z": 1.0}
    return c


def entity_docs(numbers, templates):
    """The number entity: .ent (no components of its own) and .app with one appearance "n<number>" per number:
    the ring and its digits."""
    tpl = json.load(open(templates, encoding="utf-8"))
    app = copy.deepcopy(tpl["app"])
    rc = app["Data"]["RootChunk"]
    rc["baseEntity"]["DepotPath"]["$value"] = ENTITY
    look_tpl = rc["appearances"][0]
    looks = []
    for n in sorted(numbers):
        look = copy.deepcopy(look_tpl)
        d = look["Data"]
        d["name"] = cname(f"n{n}")
        d["proxyMesh"] = {"DepotPath": {"$type": "ResourcePath", "$storage": "uint64", "$value": "0"}, "Flags": "Soft"}
        comps = [mesh_component(tpl["mesh_component"], "ring", DEPOT_DIR + r"\ltbf_pad_ring.mesh", 0.0, LIFT, 0)]
        scale = DIGIT_SCALE[len(str(n))]
        for i, (digit, x) in enumerate(digit_offsets(n)):
            comps.append(mesh_component(tpl["mesh_component"], f"digit{i}",
                                        DEPOT_DIR + rf"\ltbf_pad_digit_{digit}.mesh", x, 2 * LIFT, i + 1, scale))
        d["components"] = comps
        looks.append(look)
    rc["appearances"] = looks
    ent = copy.deepcopy(tpl["ent"])
    erc = ent["Data"]["RootChunk"]
    erc["components"] = []
    first = erc["appearances"][0]
    erc["appearances"] = []
    for n in sorted(numbers):
        a = copy.deepcopy(first)
        a["appearanceName"] = cname(f"n{n}")
        a["name"] = cname(f"n{n}")
        a["appearanceResource"]["DepotPath"]["$value"] = ENTITY[:-4] + ".app"
        erc["appearances"].append(a)
    erc["defaultAppearance"] = cname(f"n{min(numbers)}")
    return renumber(ent), renumber(app)


def write_entity(numbers, work):
    os.makedirs(work, exist_ok=True)
    ent, app = entity_docs(numbers, os.path.join(HERE, "pad_templates.json"))
    files = []
    for doc, ext in ((ent, ".ent"), (app, ".app")):
        path = os.path.join(work, "ltbf_pad_number" + ext + ".json")
        json.dump(doc, open(path, "w", encoding="utf-8"), indent=1)
        files.append(path)
    out = os.path.join(SOURCE, *DEPOT_DIR.split("\\"))
    r = subprocess.run([paths.WOLVENKIT, "cr2w", "-d", *files, "-o", out], capture_output=True, text=True)
    if r.returncode != 0 or "Error" in r.stdout:
        raise SystemExit(f"WolvenKit cr2w -d failed:\n{r.stdout[-2000:]}{r.stderr[-1000:]}")
    for ext in (".ent", ".app"):
        if not os.path.exists(os.path.join(out, "ltbf_pad_number" + ext)):
            raise SystemExit(f"not made: ltbf_pad_number{ext}")


def signs_cmd(args):
    data = json.load(open(os.path.join(args.work, "placements.json")))
    placements = data["placements"] if isinstance(data, dict) else data
    _, rows = read_tsv(args.tsv)
    if any(not r[8] for r in rows):
        raise SystemExit("the TSV has pads without a number: run `pad_numbers.py number` first")
    signs, bare = find_signs(rows, placements)
    doc = {
        "comment": "Pad number signs (tools/pads/pad_numbers.py signs; pad_sector.py places them): one "
                   "ltbf_pad_number.ent node per pad at its vanilla marking, appearance n<number>. hide: the vanilla "
                   "28 sign under it (hidden_nodes.txt).",
        "entity": ENTITY,
        "streaming_distance": args.streaming_distance,
        "signs": sorted(signs, key=lambda s: s["number"]),
    }
    with open(SIGNS, "w", encoding="utf-8", newline="\n") as f:
        json.dump(doc, f, indent=1)
        f.write("\n")
    write_hidden(signs)
    write_entity({s["number"] for s in signs}, os.path.join(paths.TMP, "pad_numbers"))
    over = {}
    for s in signs:
        over[s["over"]] = over.get(s["over"], 0) + 1
    print(f"{len(signs)} signs {over}; no marking (not painted): {len(bare)} {bare}", file=sys.stderr)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    n = sub.add_parser("number")
    n.add_argument("--tsv", default=TSV)
    s = sub.add_parser("signs")
    s.add_argument("--work", required=True, help="pads.py work dir (placements.json)")
    s.add_argument("--tsv", default=TSV)
    s.add_argument("--streaming-distance", type=float, default=400.0)
    args = ap.parse_args()
    if args.cmd == "number":
        number_tsv(args.tsv)
    else:
        signs_cmd(args)


if __name__ == "__main__":
    main()
